#!/usr/bin/env python3
"""Write a nested, 2D blockMeshDict for the NASA backward-step study."""

from __future__ import annotations

import argparse
from pathlib import Path


H = 1.0
SPAN = 0.01 * H
# The NASA TMR schematic shows freestream/symmetry sections before viscous
# walls begin at x/H=-110.  The inlet/outlet extents here are explicit study
# choices based on that schematic, not a NASA coordinate-grid file.
X = (-180.0 * H, -110.0 * H, -4.0 * H, 0.0, 10.0 * H, 50.0 * H)
Y = (-1.0 * H, 0.0, 4.0 * H, 8.0 * H)

LEVELS = {
    "coarse": {"x": (100, 212, 40, 200, 320), "y": 64, "lower": 32},
    "medium": {"x": (150, 318, 60, 300, 480), "y": 96, "lower": 48},
    "fine": {"x": (225, 477, 90, 450, 720), "y": 144, "lower": 72},
}


def vertex(i: int, j: int, k: int) -> int:
    return i * 8 + j * 2 + k


def hex_vertices(i: int, j: int) -> tuple[int, ...]:
    a = vertex(i, j, 0)
    b = vertex(i + 1, j, 0)
    c = vertex(i + 1, j + 1, 0)
    d = vertex(i, j + 1, 0)
    return (a, b, c, d, a + 1, b + 1, c + 1, d + 1)


def face(i: int, j: int, side: str) -> tuple[int, ...]:
    a, b, c, d, az, bz, cz, dz = hex_vertices(i, j)
    return {
        "west": (a, az, dz, d),
        "east": (b, c, cz, bz),
        "bottom": (a, b, bz, az),
        "top": (d, dz, cz, c),
        "front": (a, d, c, b),
        "back": (az, bz, cz, dz),
    }[side]


def render(level: str) -> str:
    spec = LEVELS[level]
    blocks: list[str] = []
    all_blocks: list[tuple[int, int]] = []

    for i, nx in enumerate(spec["x"]):
        for j in (1, 2):
            ny = spec["y"]
            x_grade = 1
            # Conformal blockMesh interfaces require matching node positions
            # across the symmetry-to-wall transition, so this sizing is carried
            # through the upstream symmetry block as a mesh convenience only.
            y_grade = 20 if j == 1 else 0.05
            verts = " ".join(map(str, hex_vertices(i, j)))
            blocks.append(
                f"    hex ({verts}) ({nx} {ny} 1) "
                f"simpleGrading ({x_grade} {y_grade} 1)"
            )
            all_blocks.append((i, j))

        if i >= 3:
            nx = spec["x"][i]
            ny = spec["lower"]
            verts = " ".join(map(str, hex_vertices(i, 0)))
            blocks.append(
                f"    hex ({verts}) ({nx} {ny} 1) simpleGrading (1 20 1)"
            )
            all_blocks.append((i, 0))

    def faces(items: list[tuple[int, int, str]]) -> str:
        return "\n".join(
            "            (" + " ".join(map(str, face(i, j, side))) + ")"
            for i, j, side in items
        )

    patches = {
        "inlet": [(0, 1, "west"), (0, 2, "west")],
        "outlet": [(5 - 1, 0, "east"), (5 - 1, 1, "east"), (5 - 1, 2, "east")],
        "upstreamWall": [(1, 1, "bottom"), (2, 1, "bottom")],
        "lowerWall": [(3, 0, "bottom"), (4, 0, "bottom")],
        "stepWall": [(3, 0, "west")],
        "topWall": [(i, 2, "top") for i in range(1, 5)],
        "symmetry": [(0, 1, "bottom"), (0, 2, "top")],
        "frontAndBack": [
            (i, j, side)
            for i, j in all_blocks
            for side in ("front", "back")
        ],
    }

    patch_types = {
        "inlet": "patch",
        "outlet": "patch",
        "upstreamWall": "wall",
        "lowerWall": "wall",
        "stepWall": "wall",
        "topWall": "wall",
        "symmetry": "symmetry",
        "frontAndBack": "empty",
    }

    vertices = []
    for i, x in enumerate(X):
        for j, y in enumerate(Y):
            for z in (0.0, SPAN):
                vertices.append((vertex(i, j, 0), x, y, z))

    lines = [
        "/* Generated by scripts/generate_block_mesh.py; do not hand-edit. */",
        "FoamFile { format ascii; class dictionary; object blockMeshDict; }",
        "convertToMeters 1;",
        "vertices",
        "(",
    ]
    lines.extend(f"    ({x:.9g} {y:.9g} {z:.9g}) // {idx}" for idx, x, y, z in vertices)
    lines.extend([ ");", "blocks", "(", *blocks, ");", "edges ();", "boundary", "("])

    for name, patch_faces in patches.items():
        lines.extend(
            [
                f"    {name}",
                "    {",
                f"        type {patch_types[name]};",
                "        faces",
                "        (",
                faces(patch_faces),
                "        );",
                "    }",
            ]
        )

    lines.extend([ ");", "mergePatchPairs ();", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--level", choices=LEVELS, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(render(args.level), encoding="utf-8")
    cell_count = sum(LEVELS[args.level]["x"]) * 2 * LEVELS[args.level]["y"]
    cell_count += sum(LEVELS[args.level]["x"][3:]) * LEVELS[args.level]["lower"]
    print(f"level={args.level} estimated_cells={cell_count} output={args.output}")


if __name__ == "__main__":
    main()
